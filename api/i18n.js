  var D = window.CALCAR_I18N = { ru: RU, en: EN };
  function norm(s) { return String(s).replace(/\s+/g, ' ').trim(); }
  window.t = function (s, l) {
    l = l || lang();
    if (l === 'ua') return s;
    var d = D[l];
    if (!d) return s;
    return d[norm(s)] || s;
  };

  /* делегування на document: працює незалежно від того, коли зʼявився хедер
     і чи встиг markSwitch відпрацювати */
  document.addEventListener('click', function (e) {
    var menu = document.getElementById('langMenu');
    if (!menu) return;
    var pick = e.target.closest ? e.target.closest('.lang-menu button') : null;
    if (pick && pick.dataset.lang) {
      e.preventDefault();
      try { localStorage.setItem(LS, pick.dataset.lang); } catch (err) {}
      location.reload();
      return;
    }
    var btn = e.target.closest ? e.target.closest('#langBtn') : null;
    if (btn) { e.preventDefault(); menu.classList.toggle('open'); return; }
    menu.classList.remove('open');
  });

  function markSwitch() {
    var l = lang();
    var btn = document.getElementById('langBtn');
    var menu = document.getElementById('langMenu');
    if (!btn || !menu) return;
    var code = { ua: 'UA', ru: 'RU', en: 'EN' }[l] + ' ';
    if (btn.firstChild && btn.firstChild.nodeType === 3) btn.firstChild.nodeValue = code;
    menu.querySelectorAll('button').forEach(function (b) {
      b.classList.toggle('on', b.dataset.lang === l);
    });
  }

  function apply() {
    var l = lang();
    document.documentElement.lang = { ua: 'uk', ru: 'ru', en: 'en' }[l];
    if (l !== 'ua') {
      var d = D[l];
      var w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null);
      var nodes = [], n;
      while ((n = w.nextNode())) nodes.push(n);
      nodes.forEach(function (nd) {
        var k = norm(nd.nodeValue || '');
        if (k && d[k]) {
          var lead = (nd.nodeValue.match(/^\s*/) || [''])[0];
          var tail = (nd.nodeValue.match(/\s*$/) || [''])[0];
          nd.nodeValue = lead + d[k] + tail;
        }
      });
      ['placeholder', 'title', 'aria-label', 'alt'].forEach(function (a) {
        document.querySelectorAll('[' + a + ']').forEach(function (el) {
          var k = norm(el.getAttribute(a) || '');
          if (k && d[k]) el.setAttribute(a, d[k]);
        });
      });
      var tk = norm(document.title);
      if (d[tk]) document.title = d[tk];
    }
    markSwitch();
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', apply);
  else apply();
